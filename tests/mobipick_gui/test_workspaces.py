from pathlib import Path

import pytest
import yaml

from mobipick_gui.workspaces import RosWorkspace, WorkspaceRegistry


def test_create_save_and_reload_workspace_registry(tmp_path):
    registry_path = tmp_path / 'config' / 'workspaces.yaml'
    master = tmp_path / 'ros1_ws'
    registry = WorkspaceRegistry(registry_path)
    registry.master_folder = str(master)

    base = registry.create('base_ws')
    child = registry.create('child_ws', extends=['base_ws'])
    child.image = 'example/child:latest'
    registry.upsert(child)
    registry.active = child.name
    registry.save()

    assert (base.directory / 'src').is_dir()
    assert (child.directory / 'src').is_dir()
    assert not child.is_built

    loaded = WorkspaceRegistry(registry_path).load()
    assert loaded.active == 'child_ws'
    assert loaded.get('child_ws').extends == ['base_ws']
    assert loaded.get('child_ws').image == 'example/child:latest'


def test_runtime_environment_mounts_master_at_canonical_ros_ws(tmp_path):
    master = tmp_path / 'ros1_ws'
    container_root = Path('/home/test/ros_ws')
    workspace = master / 'demo_ws'
    (workspace / 'src').mkdir(parents=True)
    registry = WorkspaceRegistry(
        tmp_path / 'workspaces.yaml',
        container_workspace_root=container_root,
    )
    registry.master_folder = str(master)
    registry.upsert(RosWorkspace(name='demo_ws', path=str(workspace)))
    registry.active = 'demo_ws'

    environment = registry.runtime_environment(
        empty_mount_source=tmp_path / 'empty'
    )

    assert environment['MOBIPICK_WORKSPACE_ENABLED'] == '1'
    assert environment['MOBIPICK_WORKSPACE_MOUNT_SOURCE'] == str(master)
    assert environment['MOBIPICK_WORKSPACE_MOUNT_TARGET'] == str(
        container_root
    )
    assert environment['MOBIPICK_WORKSPACE_SETUP'] == str(
        container_root / 'demo_ws' / 'devel' / 'setup.bash'
    )
    assert environment['MOBIPICK_WORKSPACE_DEVEL_PATHS'] == str(
        container_root / 'demo_ws' / 'devel'
    )
    assert environment['MOBIPICK_WORKSPACE_COMPAT_ROOTS'] == str(master)
    assert environment['MOBIPICK_WORKSPACE_BUILT'] == '0'
    assert environment['ROS_WORKSPACE'] == str(
        container_root / 'demo_ws' / 'src'
    )
    assert environment['MOBIPICK_ROS_PACKAGE_PATH'] == str(
        container_root / 'demo_ws' / 'src'
    )


