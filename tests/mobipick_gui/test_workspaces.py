def test_runtime_environment_exposes_overlay_source_paths(tmp_path):
    master = tmp_path / 'ros1_ws'
    container_root = Path('/home/test/ros_ws')
    base = RosWorkspace(name='base_ws', path=str(master / 'base_ws'))
    overlay = RosWorkspace(
        name='overlay_ws',
        path=str(master / 'overlay_ws'),
        extends=['base_ws'],
    )
    registry = WorkspaceRegistry(
        tmp_path / 'workspaces.yaml',
        container_workspace_root=container_root,
    )
    registry.master_folder = str(master)
    registry.upsert(base)
    registry.upsert(overlay)
    registry.active = overlay.name

    environment = registry.runtime_environment(
        empty_mount_source=tmp_path / 'empty'
    )

    assert environment['MOBIPICK_ROS_PACKAGE_PATH'].split(':') == [
        str(container_root / 'overlay_ws' / 'src'),
        str(container_root / 'base_ws' / 'src'),
    ]
    assert environment['MOBIPICK_WORKSPACE_DEVEL_PATHS'].split(':') == [
        str(container_root / 'base_ws' / 'devel'),
        str(container_root / 'overlay_ws' / 'devel'),
    ]


def test_empty_setup_file_is_not_treated_as_built(tmp_path):
    workspace = RosWorkspace(name='demo', path=str(tmp_path / 'demo'))
    workspace.setup_file.parent.mkdir(parents=True)
    workspace.setup_file.touch()

    assert not workspace.is_built

    workspace.setup_file.write_text('# generated by catkin\n', encoding='utf-8')
    assert workspace.is_built


