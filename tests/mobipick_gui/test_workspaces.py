def test_build_command_builds_missing_underlays_in_order(tmp_path):
    registry = WorkspaceRegistry(tmp_path / 'workspaces.yaml')
    clean = RosWorkspace(name='clean', path=str(tmp_path / 'clean'))
    common = RosWorkspace(
        name='common',
        path=str(tmp_path / 'common'),
        extends=['clean'],
    )
    gpt = RosWorkspace(
        name='gpt',
        path=str(tmp_path / 'gpt'),
        extends=['common'],
    )
    registry.upsert(clean)
    registry.upsert(common)
    registry.upsert(gpt)

    command = registry.build_command(gpt)

    clean_index = command.index(str(clean.directory))
    common_index = command.index(str(common.directory))
    gpt_index = command.index(str(gpt.directory))
    assert clean_index < common_index < gpt_index
    assert command.count('catkin build') == 3


def test_runtime_environment_maps_relocated_catkin_build(tmp_path):
    current_root = tmp_path / 'ros1_ws'
    old_root = tmp_path / 'ros_ws'
    container_root = Path('/home/test/ros_ws')
    base_dir = current_root / 'base_ws'
    base_setup = base_dir / 'devel' / 'setup.sh'
    base_setup.parent.mkdir(parents=True)
    base_setup.write_text('# generated\n', encoding='utf-8')
    workspace_dir = current_root / 'gpt_ws'
    generated_setup = (
        workspace_dir
        / 'devel'
        / '.private'
        / 'catkin_tools_prebuild'
        / 'setup.bash'
    )
    generated_setup.parent.mkdir(parents=True)
    generated_setup.write_text('# generated\n', encoding='utf-8')
    (workspace_dir / 'devel' / '.catkin').write_text(
        str(old_root / 'gpt_ws' / 'src' / 'mobipick_gpt'),
        encoding='utf-8',
    )
    public_setup = workspace_dir / 'devel' / 'setup.bash'
    public_setup.symlink_to(
        old_root
        / 'gpt_ws'
        / 'devel'
        / '.private'
        / 'catkin_tools_prebuild'
        / 'setup.bash'
    )
    registry = WorkspaceRegistry(
        tmp_path / 'workspaces.yaml',
        container_workspace_root=container_root,
    )
    registry.master_folder = str(current_root)
    registry.upsert(RosWorkspace(name='base_ws', path=str(base_dir)))
    registry.upsert(
        RosWorkspace(
            name='gpt_ws',
            path=str(workspace_dir),
            extends=['base_ws'],
        )
    )
    registry.active = 'gpt_ws'

    environment = registry.runtime_environment(
        empty_mount_source=tmp_path / 'empty'
    )

    assert environment['MOBIPICK_WORKSPACE_MOUNT_SOURCE'] == str(current_root)
    assert environment['MOBIPICK_WORKSPACE_MOUNT_TARGET'] == str(
        container_root
    )
    assert environment['MOBIPICK_WORKSPACE_COMPAT_ROOTS'].split(':') == [
        str(current_root),
        str(old_root),
    ]
    assert environment['ROS_WORKSPACE'] == str(
        container_root / 'gpt_ws' / 'src'
    )
    assert environment['MOBIPICK_ROS_PACKAGE_PATH'] == str(
        container_root / 'gpt_ws' / 'src' / 'mobipick_gpt'
    )
    assert registry.is_runtime_built(registry.get('gpt_ws'))


def test_legacy_selector_migrates_active_workspace_and_profiles(
    tmp_path,
    monkeypatch,
):
    home = tmp_path / 'home'
    monkeypatch.setenv('HOME', str(home))
    resources = tmp_path / 'resources'
    private = resources / 'private'
    buttons = private / 'button_configs'
    experiments = private / 'experiments'
    buttons.mkdir(parents=True)
    experiments.mkdir()
    (home / 'ros1_ws' / 'base_ws' / 'src').mkdir(parents=True)
    (home / 'ros1_ws' / 'child_ws' / 'src').mkdir(parents=True)
    (buttons / 'button_commands_child_ws.yaml').write_text(
        'buttons: []\n',
        encoding='utf-8',
    )
    (experiments / 'child_ws_experiments.yaml').write_text(
        'timeline: []\n',
        encoding='utf-8',
    )
    (private / 'config.yml').write_text(
        yaml.safe_dump(
            {
                'commands': {
                    'child_ws': ['roslaunch', 'demo', 'demo.launch']
                }
            }
        ),
        encoding='utf-8',
    )
    (private / 'select_ros1_ws.sh').write_text(
        '''
DESIRED_NUMBER=1
rws_list=(
    $HOME/ros_ws/base_ws/src # base
    $HOME/ros_ws/child_ws/src # extends #0
)
''',
        encoding='utf-8',
    )

    registry = WorkspaceRegistry(
        tmp_path / 'registry.yaml',
        resources_root=resources,
    ).load()

    child = registry.get('child_ws')
    assert registry.active == 'child_ws'
    assert child.extends == ['base_ws']
    assert child.button_config.endswith('button_commands_child_ws.yaml')
    assert child.launch_config.endswith('child_ws_experiments.yaml')
    assert child.sim_command == 'roslaunch demo demo.launch'


