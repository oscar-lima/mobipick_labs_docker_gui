def test_built_overlay_adds_catkin_package_paths_not_source_root(tmp_path):
    container_root = Path('/home/test/ros_ws')
    base = RosWorkspace(name='base', path=str(tmp_path / 'base'))
    overlay = RosWorkspace(
        name='overlay',
        path=str(tmp_path / 'overlay'),
        extends=['base'],
    )
    for workspace in (base, overlay):
        setup_sh = workspace.directory / 'devel' / 'setup.sh'
        setup_sh.parent.mkdir(parents=True)
        setup_sh.write_text('# generated by catkin\n', encoding='utf-8')
    overlay_packages = [
        overlay.directory / 'src' / 'first_package',
        overlay.directory / 'src' / 'nested' / 'second_package',
    ]
    (overlay.directory / 'devel' / '.catkin').write_text(
        ';'.join(str(path) for path in overlay_packages),
        encoding='utf-8',
    )
    registry = WorkspaceRegistry(
        tmp_path / 'workspaces.yaml',
        container_workspace_root=container_root,
    )
    registry.upsert(base)
    registry.upsert(overlay)
    registry.active = overlay.name

    environment = registry.runtime_environment(
        empty_mount_source=tmp_path / 'empty'
    )

    assert environment['MOBIPICK_ROS_PACKAGE_PATH'].split(':') == [
        str(container_root / 'overlay' / 'src' / 'first_package'),
        str(
            container_root
            / 'overlay'
            / 'src'
            / 'nested'
            / 'second_package'
        ),
    ]
    assert str(container_root / 'overlay' / 'src') not in (
        environment['MOBIPICK_ROS_PACKAGE_PATH'].split(':')
    )


def test_registry_rejects_inheritance_cycles(tmp_path):
    registry = WorkspaceRegistry(tmp_path / 'workspaces.yaml')
    registry.upsert(RosWorkspace(name='first', path=str(tmp_path / 'first')))
    registry.upsert(
        RosWorkspace(
            name='second',
            path=str(tmp_path / 'second'),
            extends=['first'],
        )
    )

    with pytest.raises(ValueError, match='cycle'):
        registry.upsert(
            RosWorkspace(
                name='first',
                path=str(tmp_path / 'first'),
                extends=['second'],
            )
        )


